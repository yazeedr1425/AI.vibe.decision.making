-- ============================================================
-- الفئة صارت اختيارية
--
-- انحذف اختيار "نوع القرار" من الواجهة: الأسئلة تُولّد من الخيارات
-- نفسها، فما عاد للفئة دور. لكن العمود NOT NULL، فبدون هذا التغيير
-- كل حفظ يفشل بمجرد ما ينحذف المنتقي.
--
-- نكتفي بإسقاط NOT NULL ولا نلمس قيد CHECK: في SQL قيد CHECK على
-- قيمة NULL يعطي UNKNOWN لا FALSE، فيمرّ. والقرارات القديمة تحتفظ
-- بفئتها كما هي.
-- ============================================================

alter table public.decisions
  alter column category drop not null;

comment on column public.decisions.category is
  'فئة القرار — تاريخية. القرارات الجديدة تُحفظ بلا فئة بعد ما صارت الأسئلة تُولّد من الخيارات.';
