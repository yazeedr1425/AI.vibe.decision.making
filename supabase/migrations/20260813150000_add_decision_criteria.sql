-- ============================================================
-- حفظ معايير القرار مع القرار نفسه
--
-- المعايير والأسئلة صارت تُولّد من خيارات كل قرار على حدة بدل ما
-- تجي من قالب الفئة الثابت. يعني ما عادت خاصية للفئة — صارت جزءاً
-- من القرار.
--
-- بدون هذا العمود ينكسر شيئان بصمت:
--
--   ١) إعادة عرض قرار قديم: صف answers يخزّن question_key مثل
--      "cravings_level"، وهذا المفتاح مولّد لتلك المفاضلة تحديداً.
--      بدون نسخة من الأسئلة ما نعرف نص السؤال ولا خياراته، فيصير
--      السجل مفاتيح خام بلا معنى.
--
--   ٢) السجل المُمرَّر للنموذج في api/decide: describeAnswers تبحث
--      عن السؤال داخل القالب، وما تلقاه، فتسقط لسطر "key: value".
--      النموذج يقرأ رموزاً بدل جُمل.
--
-- jsonb لا أعمدة: الشكل عقد بين المحرك والواجهة (criteria و
-- questions و moodCriteria)، وتفكيكه لجداول يعني ثلاثة جداول
-- وأربع وصلات لقراءة قرار واحد، بلا أي استعلام يحتاج ذلك.
-- ============================================================

alter table public.decisions
  add column if not exists criteria jsonb;

comment on column public.decisions.criteria is
  'نسخة المعايير والأسئلة وقت اتخاذ القرار: {criteria, questions, moodCriteria, generated}. فارغ للقرارات القديمة اللي انبنت على القوالب الثابتة.';
