// كشف القرار الأكبر من أدوات الحسم العادية.
//
// "أستقيل؟" ما تجاوبه ثلاثة أسئلة وشبكة تقييم — يحتاج تفكيكاً.
// الكشف محلي بلا نداء: يشتغل مع كل حرف يكتبه المستخدم، ونداء شبكة
// هنا يكلف مالاً وزمناً على فحص أغلب نتائجه "لا، قرار عادي".
//
// قائمة كلمات مقصودة لا تصنيف ذكي: قرارات المصير مفرداتها محدودة
// (وظيفة، زواج، هجرة، عقار، دراسة...) والقائمة تمسكها بصفر تكلفة.
// الخطأ المقبول هنا هو الفائت لا الزائف — بانر "قرارك مصيري" فوق
// برجر وسوشي يضحّك الناس على التطبيق، وفوات حالة نادرة الصياغة
// يغطيه اختيار المستخدم فئة "قرار مصيري" بنفسه.

import { normalizeArabic } from "@/lib/text/arabic";

// كلمات كاملة بعد التطبيع (أ→ا، ة→ه، بلا تشكيل)
const WORDS = new Set([
  "بيت",
  "شقه",
  "عقار",
  "ارض",
  "قرض",
  "بلد",
  "شركه",
  "محل",
  "جامعه",
  "كليه",
  "ماجستير",
  "دكتوراه",
  "ابتعث",
  "الابتعاث",
  "بعثه",
  "هجره",
  "اهاجر",
  "نهاجر",
  "اتزوج",
  "نتزوج",
  "زواج",
  "خطبه",
  "اخطب",
  "طلاق",
  "اطلق",
  "استقالتي",
  "استقالته",
]);

// جذور تُطابق بداية الكلمة — أربعة أحرف فأكثر حتى ما تبلع كلمة
// بريئة. "بيت" ما تصلح جذراً: "بيتزا" تبدأ بها.
const STEMS = [
  "استقيل",
  "استقال",
  "وظيف", // وظيفه، وظيفتي، الوظيفه (بعد قص ال)
  "مشروع", // مشروعي، مشروعك
  "تخصص",
  "استثمر",
  "استثمار",
];

const tokenMatches = (token) => {
  // "الوظيفه" — نجرب الكلمة ومجردة من ال
  const forms = token.startsWith("ال") ? [token, token.slice(2)] : [token];
  return forms.some(
    (form) => WORDS.has(form) || STEMS.some((stem) => form.startsWith(stem)),
  );
};

/**
 * @param {string[]} labels الخيارات المكتوبة
 * @param {string|null} categoryId اختيار المستخدم فئة "قرار مصيري"
 *   إعلان صريح بالحجم — يغني عن الكلمات
 */
export function looksOversized(labels, categoryId) {
  if (categoryId === "life") return true;
  return labels.some((label) =>
    normalizeArabic(label).split(" ").some(tokenMatches),
  );
}
