// تحويل الأرقام اللاتينية إلى هندية.
//
// الموقع كله عربي، والرقم اللاتيني وسط الجملة العربية ينشز — وأسوأ
// منه أن يختلط النظامان في سطر واحد. الخط العربي يرسم بعض الأرقام
// اللاتينية بشكل هندي وبعضها لا، فالنتيجة تعتمد على المتصفح والخط،
// وهذا ما يُترك للصدفة.
//
// المصدران اللذان يسرّبان أرقاماً لاتينية مختلفان:
//   - واجهتنا نحن — تُحوَّل عند العرض
//   - نص يكتبه النموذج — يُحوَّل عند التحقق، لأن القاعدة في البرومبت
//     رجاء والنموذج قد يخالفه، والتحويل هنا ضمان
const ARABIC = "٠١٢٣٤٥٦٧٨٩";

export function toArabicDigits(value) {
  return String(value ?? "").replace(/[0-9]/g, (d) => ARABIC[d]);
}
